#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { MARKDOWN_OUTPUT_FILES, renderReports } from "./markdown-renderer.mjs";
import { buildReportModel } from "./report-model.mjs";

const SCRIPT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FORBIDDEN_PUBLIC_PATTERNS = [
  new RegExp(["insight", "flow"].join("[ -]?"), "i"),
  new RegExp(["go", "claw"].join(""), "i"),
];

function fail(message) {
  throw new Error(message);
}

function takeOption(args, index, name) {
  const argument = args[index];
  if (argument === name) {
    if (index + 1 >= args.length) fail(`${name} requires a value`);
    return { value: args[index + 1], consumed: 2 };
  }
  if (argument.startsWith(`${name}=`)) return { value: argument.slice(name.length + 1), consumed: 1 };
  return null;
}

function parseArguments(args) {
  const options = { repoRoot: SCRIPT_ROOT, outDir: null, upstreamRoot: undefined, check: false, sourceCheck: "auto" };
  for (let index = 0; index < args.length;) {
    const argument = args[index];
    if (argument === "--check") {
      options.check = true;
      index += 1;
      continue;
    }
    if (argument === "--help" || argument === "-h") return { help: true };
    const repo = takeOption(args, index, "--repo");
    if (repo !== null) {
      options.repoRoot = resolve(repo.value);
      index += repo.consumed;
      continue;
    }
    const out = takeOption(args, index, "--out");
    if (out !== null) {
      options.outDir = resolve(out.value);
      index += out.consumed;
      continue;
    }
    const sourceCheck = takeOption(args, index, "--source-check");
    if (sourceCheck !== null) {
      options.sourceCheck = sourceCheck.value;
      index += sourceCheck.consumed;
      continue;
    }
    const upstream = takeOption(args, index, "--upstream-root");
    if (upstream !== null) {
      options.upstreamRoot = resolve(upstream.value);
      index += upstream.consumed;
      continue;
    }
    fail(`unknown argument ${argument}`);
  }
  options.outDir ??= options.repoRoot;
  return options;
}

function scanPublicSafety(markdown, lang) {
  for (const pattern of FORBIDDEN_PUBLIC_PATTERNS) {
    if (pattern.test(markdown)) fail(`${lang}: generated Markdown contains a forbidden private-comparison identifier`);
  }
}

function outputEntries(rendered, outDir) {
  return Object.entries(MARKDOWN_OUTPUT_FILES).map(([lang, filename]) => ({
    lang,
    filename,
    path: join(outDir, filename),
    expected: rendered[lang].markdown,
  }));
}

/**
 * Build or byte-check the two Markdown report projections.
 * @param {{repoRoot:string,outDir:string,check:boolean,sourceCheck?:"auto"|"off"|"required",upstreamRoot?:string}} options Build options.
 * @returns {{chapters:number,evidencePerLanguage:number,sourceValidation:object,mode:"built"|"checked"}} Build summary.
 */
export function buildMarkdown(options) {
  const model = buildReportModel({ repoRoot: options.repoRoot, sourceCheck: options.sourceCheck ?? "auto", upstreamRoot: options.upstreamRoot });
  const rendered = renderReports(model);
  for (const [lang, result] of Object.entries(rendered)) scanPublicSafety(result.markdown, lang);
  const entries = outputEntries(rendered, resolve(options.outDir));
  if (options.check) {
    const mismatches = [];
    for (const entry of entries) {
      if (!existsSync(entry.path)) {
        mismatches.push(`${entry.filename}: missing`);
        continue;
      }
      const actual = readFileSync(entry.path);
      const expected = Buffer.from(entry.expected, "utf8");
      if (!actual.equals(expected)) mismatches.push(`${entry.filename}: differs from generated bytes`);
    }
    if (mismatches.length > 0) fail(`Markdown check failed:\n${mismatches.map((item) => `- ${item}`).join("\n")}`);
  } else {
    mkdirSync(resolve(options.outDir), { recursive: true });
    for (const entry of entries) writeFileSync(entry.path, entry.expected, "utf8");
  }
  return {
    chapters: model.languages.en.manifest.chapters.length,
    evidencePerLanguage: rendered.en.evidenceIds.length,
    sourceValidation: model.sourceValidation,
    mode: options.check ? "checked" : "built",
  };
}

/**
 * Command-line entrypoint.
 * @param {string[]} args Process arguments after the executable and script path.
 * @returns {void}
 */
export function main(args) {
  const options = parseArguments(args);
  if (options.help) {
    process.stdout.write("Usage: node scripts/build-markdown.mjs [--repo PATH] [--out PATH] [--upstream-root PATH] [--check] [--source-check auto|off|required]\n");
    return;
  }
  const summary = buildMarkdown(options);
  const source = summary.sourceValidation.performed ? `source=${summary.sourceValidation.items}-items-verified` : `source=${summary.sourceValidation.reason}`;
  process.stdout.write(`markdown-${summary.mode}-ok chapters=${summary.chapters} evidence-per-language=${summary.evidencePerLanguage} ${source}\n`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
